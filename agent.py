# ============================================================
# agent.py | THE AGENT: MODEL + TOOLS + SYSTEM PROMPT
# ============================================================
#
# Pattern: @tool functions + create_agent(model, tools, system_prompt)
#
# The model gets ONE main tool, run_sql_query, and WRITES THE SQL ITSELF
# from your question. This is called "Text-to-SQL".
#
# Tools:
#   run_sql_query(sql)              → always. Read-only.
#   list_tables()                   → only for big databases ("lookup" mode)
#   describe_tables(table_names)    → only for big databases ("lookup" mode)
#   propose_db_change(sql, reason)  → only if ALLOW_DB_CHANGES=true in .env.
#                                     It changes NOTHING. It waits for a human.
#
# You do NOT edit this file. Use .env and knowledge.md.
# ============================================================

from langchain.agents import create_agent
from langchain.chat_models import init_chat_model
from langchain.tools import tool

import database
import settings


# ============================================================
# THE MODEL
# ============================================================
# init_chat_model("provider:model") → one line works for OpenAI, Azure OpenAI,
# Anthropic (Claude), AWS Bedrock, Groq, Google and more. You choose in .env.
# model_name → used by the connection screen to test a model before saving it.
#              Normally empty, which means "use LLM_MODEL from .env".
def build_llm(model_name=""):
    if model_name == "":
        model_name = settings.LLM_MODEL
    options = {}
    if settings.LLM_TEMPERATURE != "":
        options["temperature"] = float(settings.LLM_TEMPERATURE)
    # Newer OpenAI models (GPT-5 and later) only allow tools on the newer
    # "Responses" API, so we use it for OpenAI. Turn off with OPENAI_RESPONSES_API=false
    if model_name.startswith("openai:") and settings.OPENAI_RESPONSES_API:
        options["use_responses_api"] = True
    # Azure calls the model by your DEPLOYMENT name, so we pass it through
    if model_name.startswith("azure_openai:"):
        options["azure_deployment"] = model_name.split(":", 1)[1]
    return init_chat_model(model_name, **options)


# ============================================================
# THE KNOWLEDGE FILE (your business words, example questions)
# ============================================================
def read_knowledge():
    if not settings.KNOWLEDGE_FILE.exists():
        return "(No knowledge file. Add knowledge.md to make answers more accurate.)"
    return settings.KNOWLEDGE_FILE.read_text(encoding="utf-8")


RULES = """
RULES:
- Always get numbers by running SQL with the run_sql_query tool. Never guess or invent data.
- Use table names exactly as written above, including the schema part (for example sales.customer).
- Only use columns you have actually seen. Never guess a column name.
- Every column listed holds data, whatever its type. Prefer names (e.g. a Name column) over IDs in answers.
- Run ONE query at a time, and only the queries needed for the user's exact question.
- Answer ONLY from the result whose "RESULT OF QUERY" matches the question. Check "Rows returned".
- If a result says only the first rows are shown, say the list is cut off. Use COUNT(*) for totals.
- If a query returns an error, read the error, fix the SQL and try again (at most 3 tries).
- If the question is unclear (which year? which department?), ask ONE short question instead of guessing.
- Answer in short, clear business English. Mention the key numbers.
- If the question cannot be answered from this data, say so honestly.
"""

LOOKUP_RULES = """
- This database is big, so you only see table NAMES above.
- Before writing SQL, call describe_tables with the tables you need to see their
  columns and joins. Call list_tables if you are not sure which table holds the data.
"""

READ_ONLY_RULES = """
- You have READ-ONLY access. You cannot add, change or delete data.
  If asked to change data, politely explain that you only have read access.
"""

CHANGE_RULES = """
- To add or change data, use the propose_db_change tool. It does NOT run the change.
  A human must approve it first. Never tell the user a change is done until it is approved.
- Before proposing a change, first run a SELECT to check the current value.
"""


# ============================================================
# THE SYSTEM PROMPT: built from the database + knowledge.md
# ============================================================
def build_system_prompt(mode):
    prompt = "You are QueryDost, a data assistant. You answer questions by writing SQL for a "
    prompt = prompt + database.get_dialect_name() + " database.\n\n"

    if mode == "full":
        prompt = prompt + "DATABASE TABLES:\n" + database.get_full_schema_text() + "\n\n"
    else:
        prompt = prompt + "TABLE NAMES:\n" + ", ".join(database.list_tables()) + "\n\n"

    prompt = prompt + "BUSINESS KNOWLEDGE (from the people who own this data):\n"
    prompt = prompt + read_knowledge() + "\n"
    prompt = prompt + RULES
    if mode == "lookup":
        prompt = prompt + LOOKUP_RULES
    if settings.ALLOW_DB_CHANGES:
        prompt = prompt + CHANGE_RULES
    else:
        prompt = prompt + READ_ONLY_RULES
    return prompt


# Turn a query result into simple text the model can read.
# The SQL and the row count go at the top, so with several queries the model
# can never mix up which result belongs to which query.
def result_as_text(sql, result):
    text = "RESULT OF QUERY: " + sql + "\n"
    text = text + "Rows returned: " + str(len(result["rows"])) + "\n"
    text = text + "Columns: " + ", ".join(result["columns"]) + "\n"
    for r in range(len(result["rows"])):
        text = text + str(result["rows"][r]) + "\n"
    if len(result["rows"]) == 0:
        text = text + "(No rows matched.)"
    if result["truncated"]:
        text = text + "(Only the first " + str(settings.MAX_ROWS) + " rows are shown. The list is cut off.)"
    return text


# ============================================================
# BUILD ONE AGENT FOR ONE BROWSER TAB
# ============================================================
# session → this tab's own notebook: {"queries": [...], "pending": [...]}
# The tools are written INSIDE this function so each tab writes to its own
# notebook. Two people using the app never see each other's queries.
def build_agent(session):

    # @tool             → turns the function into a tool the model can call
    # (sql: str) -> str → the model sends SQL as text and gets the result back as text
    # """docstring"""   → what the model reads to decide when to use the tool
    @tool
    def run_sql_query(sql: str) -> str:
        """Run ONE read-only SQL SELECT query on the database and get the rows back.
        Use this for ANY question about the data. Write the SQL yourself."""
        result = database.run_read_query(sql)
        session["queries"].append({"sql": sql, "result": result})
        if not result["ok"]:
            return "ERROR: " + result["error"] + ". Fix the SQL and try again."
        return result_as_text(sql, result)

    @tool
    def list_tables() -> str:
        """List every table and view you are allowed to query."""
        return ", ".join(database.list_tables())

    @tool
    def describe_tables(table_names: str) -> str:
        """Get columns, types, joins and sample rows for one or more tables.
        table_names: comma separated, exactly as listed, e.g. 'sales.customer, person.person'."""
        names = table_names.split(",")
        parts = []
        for i in range(len(names)):
            real_name = database.find_table(names[i])
            if real_name is None:
                parts.append("Unknown table: " + names[i].strip() + ". Call list_tables.")
            else:
                parts.append(database.describe_table(real_name))
        return "\n\n".join(parts)

    @tool
    def propose_db_change(sql: str, reason: str) -> str:
        """Propose ONE INSERT or UPDATE statement (DELETE only if allowed) to change data.
        This does NOT run the change. A human must approve it first.
        'reason' is a short explanation for the human approver."""
        problem = database.check_change_sql(sql)
        if problem != "":
            database.write_audit("CHANGE REFUSED", sql, problem)
            return "REFUSED: " + problem
        session["pending"].append({"sql": sql, "reason": reason})
        database.write_audit("CHANGE PROPOSED (waiting for human)", sql, reason)
        return ("Change proposed. It is WAITING for a human to click Approve or Reject. "
                "Tell the user this. Do NOT say the change is done.")

    # tools → if a tool is not in this list, the model cannot use it. Full stop.
    mode = database.get_schema_mode()
    tools = [run_sql_query]
    if mode == "lookup":
        tools.append(list_tables)
        tools.append(describe_tables)
    if settings.ALLOW_DB_CHANGES:
        tools.append(propose_db_change)

    return create_agent(build_llm(), tools=tools, system_prompt=build_system_prompt(mode))
