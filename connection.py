# ============================================================
# connection.py | TURN PLAIN DATABASE FIELDS INTO A CONNECTION URL
# ============================================================
#
# People know their server, database, username and password.
# They do NOT know URL formats like:
#   mssql+pyodbc://user:p%40ss@server:1433/Sales?driver=ODBC+Driver+18+for+SQL+Server
#
# So QueryDost asks for plain fields and builds the URL here, safely:
#   - special characters in passwords (@ # / :) are escaped for you
#   - each database gets its own format, port and options
#
# Also here: friendly_error() turns raw database errors into plain English.
#
# You do NOT edit this file.
# ============================================================

from urllib.parse import quote, urlencode


# ------------------------------------------------------------
# Every database QueryDost knows how to build a URL for
#   label   → what the person sees in the dropdown
#   scheme  → the start of the URL (which SQLAlchemy driver to use)
#   port    → the usual port, used when the person leaves it blank
#   package → the pip package the driver needs
# ------------------------------------------------------------
DB_TYPES = {
    "sqlite": {"label": "SQLite (a single .db file)", "scheme": "sqlite", "port": "", "package": ""},
    "postgres": {"label": "PostgreSQL", "scheme": "postgresql+psycopg2", "port": "5432",
                 "package": "psycopg2-binary"},
    "mysql": {"label": "MySQL / MariaDB", "scheme": "mysql+pymysql", "port": "3306", "package": "pymysql"},
    "sqlserver": {"label": "Microsoft SQL Server / Azure SQL", "scheme": "mssql+pyodbc", "port": "1433",
                  "package": "pyodbc"},
    "oracle": {"label": "Oracle", "scheme": "oracle+oracledb", "port": "1521", "package": "oracledb"},
    "snowflake": {"label": "Snowflake", "scheme": "snowflake", "port": "",
                  "package": "snowflake-sqlalchemy"},
}

DEFAULT_SQLSERVER_DRIVER = "ODBC Driver 18 for SQL Server"


# quote(text, safe="") → escapes EVERY special character, so "p@ss#1" becomes "p%40ss%231"
def escape(text):
    return quote(str(text), safe="")


# ------------------------------------------------------------
# build_url(parts) → the connection URL
# parts is a dictionary with these keys (missing keys are fine):
#   type, file, host, port, name, user, password, role,
#   windows_login (True/False), odbc_driver, warehouse, schema
# ------------------------------------------------------------
def build_url(parts):
    db_type = parts.get("type", "")
    if db_type not in DB_TYPES:
        raise ValueError("Unknown database type: " + str(db_type) + ". Use one of: " + ", ".join(DB_TYPES))
    info = DB_TYPES[db_type]

    # ---- SQLite: just a file ----
    if db_type == "sqlite":
        file_path = parts.get("file", "") or "demo/hr_company.db"
        return "sqlite:///" + str(file_path).replace("\\", "/")

    host = parts.get("host", "").strip()
    if host == "":
        raise ValueError("Server / host is empty")
    port = str(parts.get("port", "")).strip() or info["port"]
    name = parts.get("name", "").strip()
    user = parts.get("user", "").strip()
    password = parts.get("password", "")
    windows_login = parts.get("windows_login", False)

    # ---- the login part:  user:password@  ----
    login = ""
    if not (db_type == "sqlserver" and windows_login):
        if user == "":
            raise ValueError("Username is empty")
        login = escape(user)
        if password != "":
            login = login + ":" + escape(password)
        login = login + "@"

    # ---- the server part:  host:port  ----
    # A SQL Server named instance (SERVER\SQLEXPRESS) uses no port
    server = host
    if port != "" and "\\" not in host:
        server = host + ":" + port

    options = {}
    path = "/" + escape(name) if name != "" else "/"

    if db_type == "sqlserver":
        options["driver"] = parts.get("odbc_driver", "") or DEFAULT_SQLSERVER_DRIVER
        options["TrustServerCertificate"] = "yes"
        if windows_login:
            options["Trusted_Connection"] = "yes"

    if db_type == "oracle":
        # Oracle names the database by "service name", sent as an option
        path = "/"
        if name != "":
            options["service_name"] = name

    if db_type == "snowflake":
        # Snowflake: host = account identifier, path = database/schema
        schema = parts.get("schema", "").split(",")[0].strip()
        path = "/" + escape(name)
        if schema != "":
            path = path + "/" + escape(schema)
        if parts.get("warehouse", ""):
            options["warehouse"] = parts["warehouse"]
        if parts.get("role", ""):
            options["role"] = parts["role"]

    url = info["scheme"] + "://" + login + server + path
    if len(options) > 0:
        url = url + "?" + urlencode(options)
    return url


# ------------------------------------------------------------
# friendly_error(db_type, error) → a plain-English reason + what to do
# Database errors are long and cryptic. We look for known phrases.
# ------------------------------------------------------------
ERROR_HINTS = [
    (["does not exist", "cannot open database", "unknown database", "4060"],
     "The login works, but it cannot open that database: the name is wrong, or this login has no user "
     "inside that database. Check the Database name, or ask your DBA to add the login to the database."),
    (["login failed", "password authentication failed", "access denied", "invalid username/password",
      "incorrect username or password", "28000"],
     "The database rejected the username or password. Check both, and that this login is allowed on this database."),
    (["could not translate host name", "name or service not known", "getaddrinfo", "unknown mysql server host",
      "server was not found", "no such host", "nodename nor servname"],
     "The server name could not be found. Check the Server / host field for typos."),
    (["timeout", "timed out", "connection refused", "can't connect", "could not connect", "tcp provider",
      "network-related", "unable to connect", "08001"],
     "The server did not answer. Check the host and port, that the database is running, and that "
     "you are on the company VPN if it needs one."),
    (["data source name not found", "can't open lib", "im002"],
     "The ODBC driver for SQL Server is not installed. Install 'ODBC Driver 18 for SQL Server' from Microsoft, "
     "or type the driver name you have in the ODBC driver field."),
    (["certificate", "ssl"],
     "There is a security certificate problem. Ask your DBA whether the server needs special SSL settings."),
    (["unable to open database file"],
     "The SQLite file was not found. Check the file path."),
]


def friendly_error(db_type, error):
    text = str(error)
    lower = text.lower()

    # A missing Python driver is the most common first-time problem
    if "no module named" in lower or "can't load plugin" in lower:
        package = DB_TYPES.get(db_type, {}).get("package", "")
        if package != "":
            return "The Python driver for this database is missing. Run:  pip install " + package
        return "A Python package is missing: " + text.split("\n")[0]

    for i in range(len(ERROR_HINTS)):
        phrases = ERROR_HINTS[i][0]
        for p in range(len(phrases)):
            if phrases[p] in lower:
                return ERROR_HINTS[i][1]
    return "Could not connect: " + text.split("\n")[0][:300]
